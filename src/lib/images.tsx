import { useLayoutEffect, useRef } from "react";
import { useTranslation } from "react-i18next";
import { useTheme } from "@/components/theme-provider";
import {
  drawPreloadedZapLogo,
  preloadZapLogo,
  ZAP_LOGO_HEIGHT,
  ZAP_LOGO_WIDTH,
} from "@/lib/zapLogo";

interface ZapLogoProps {
  width?: number;
}

export function ZapLogo({ width = ZAP_LOGO_WIDTH }: ZapLogoProps = {}) {
  const { t } = useTranslation();
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const { resolvedTheme } = useTheme();
  const height = (width / ZAP_LOGO_WIDTH) * ZAP_LOGO_HEIGHT;

  useLayoutEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas || typeof CanvasRenderingContext2D === "undefined") return;

    let active = true;
    const draw = () => {
      if (active) drawPreloadedZapLogo(canvas);
    };

    if (!drawPreloadedZapLogo(canvas)) {
      void preloadZapLogo().then(draw);
    }

    return () => {
      active = false;
    };
  }, [resolvedTheme]);

  if (resolvedTheme === "light") {
    return (
      <img
        src={`${__APP_BASE_PATH__}lockup-light.webp`}
        alt={t("accessibility.logo")}
        width={ZAP_LOGO_WIDTH}
        height={ZAP_LOGO_HEIGHT}
        className="object-contain"
        style={{ width, height }}
      />
    );
  }

  return (
    <canvas
      ref={canvasRef}
      role="img"
      aria-label={t("accessibility.logo")}
      width={ZAP_LOGO_WIDTH}
      height={ZAP_LOGO_HEIGHT}
      style={{ width, height }}
    />
  );
}

